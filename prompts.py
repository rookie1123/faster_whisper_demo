"""initial_prompt 词表：给 Whisper 提供上下文和参考词。

用法（两个脚本都支持）:
    python eval_zh.py samples/my_audio.mp3 samples/my_audio.txt --prompt-name tech
    python transcribe.py samples/my_audio.mp3 --prompt-name tech

原理:
    Whisper 的 initial_prompt 相当于"前文"，模型会把它当成上下文来影响解码。
    把专有名词（人名、产品名、英文缩写、专业术语）写进去，可以明显降低
    同音字和生造词的错误率——例如本项目里 GitHub 被误识别成 VTOP。

注意事项:
    - 提示词不宜过长，建议控制在 200 字以内。太长的提示会挤占上下文窗口，
      个别情况下还会让模型复读提示词里的内容。
    - 词表要写"模型可能记错的词"，不需要写常见词。
    - 换领域（医疗、法律、你自己的项目）时，在下面加一条即可。

已验证的效果（2026-09-23 实测，CPU int8，详见 EXPERIMENTS.md 实验三）:
    - "zh" 这一句单独就能把 tiny 的繁体输出全部掰成简体：
      zh_tts_1 的 CER 42.0% → 6.0%，zh_tts_2 的 32.0% → 2.0%。
      也就是说，只要关心中文准确率，这条就应该默认带上。
    - 再叠加 "tech" 词表才能继续修掉专有名词（Github → GitHub、克龙 → 克隆），
      zh_tts_2 上 tiny 降到 0.0%，直接打平 small。
    - 但词表里的词若与音频内容无关，反而会轻微干扰解码
      （zh_tts_1 上从 6.0% 回退到 10.0%）。词表要贴合实际内容，不要硬塞。
    - small / medium 本来两段音频上就全对，加提示词对它们没有影响 ——
      提示词的收益主要体现在 tiny 这类弱模型上。
"""

PROMPTS = {
    # 不传任何提示，完全依赖模型自身
    "none": None,
    # 通用中文：主要作用是引导模型输出简体中文和规范标点
    "zh": "以下是普通话的句子。",
    # 技术/办公场景：本项目测试音频里出现过的词
    "tech": (
        "以下是普通话的句子。可能出现的词："
        "GitHub、服务器、模型、准确率、训练脚本、仓库、克隆、会议室、实验室。"
    ),
    # 示例模板：用你自己的会议录音时，把方括号里的内容换成真实的姓名和术语
    # "meeting": "以下是普通话的会议录音。可能出现的词：张三、李四、【项目代号】、【专业术语】。",
}
